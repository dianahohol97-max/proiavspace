export function buildFixPrompt(draftJson: string, issues: Issue[], writePrompt: string): string {
  return `${writePrompt}

ЧЕРНЕТКА, ЯКА НЕ ПРОЙШЛА ПЕРЕВІРКУ:
${draftJson}

ВИПРАВ ЛИШЕ ЦІ ПОМИЛКИ, решту залиш як є:
${issues.map((i) => `- [${i.check}] ${i.message}`).join('\n')}

Поверни повний виправлений JSON у тому ж форматі.`
}
